def observe_endpoint(endpoint: str = None):
    """
    Decorator to automatically track request metrics for Flask endpoints.

    Usage:
        @app.route('/generate', methods=['POST'])
        @observe_endpoint('/generate')
        def generate():
            ...
    """

    def decorator(func: Callable) -> Callable:
        @functools.wraps(func)
        def wrapper(*args, **kwargs):
            # Auto-detect endpoint if not provided
            ep = endpoint or func.__name__

            with track_request(ep, method="POST") as tracker:
                try:
                    result = func(*args, **kwargs)
                    # Try to extract status code from Flask response
                    if hasattr(result, "status_code"):
                        tracker.set_status(result.status_code)
                    elif isinstance(result, tuple) and len(result) >= 2:
                        tracker.set_status(result[1])
                    return result
                except Exception:
                    tracker.set_status(500)
                    raise

        return wrapper

    return decorator


