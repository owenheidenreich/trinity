# No-op fallback class (always defined for testability)
class NoOpMetric:
    """Fallback metric that does nothing when Prometheus is unavailable"""

    def labels(self, **kwargs):
        return self

    def inc(self, amount=1):
        pass

    def dec(self, amount=1):
        pass

    def set(self, value):
        pass

    def observe(self, value):
        pass

    def time(self):
        return contextmanager(lambda: (yield))()


